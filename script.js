const root = document.documentElement;
const languageSelect = document.getElementById("languageSelect");
const themeToggle = document.getElementById("themeToggle");
const toast = document.getElementById("toast");
const progress = document.getElementById("progress");
const themeColor = document.querySelector('meta[name="theme-color"]');

const storage = {
  get(key) {
    try { return localStorage.getItem(key); } catch { return null; }
  },
  set(key, value) {
    try { localStorage.setItem(key, value); } catch { /* Storage is optional. */ }
  }
};

let language = storage.get("pf-language") || "de";
const pdfs = {
  de: "paul-freyhofer-cv-de.pdf",
  en: "paul-freyhofer-cv-en.pdf",
  fr: "paul-freyhofer-cv-fr.pdf",
  es: "paul-freyhofer-cv-es.pdf"
};

function setLanguage(lang) {
  language = translations[lang] ? lang : "de";
  const copy = translations[language];
  root.lang = language;
  languageSelect.value = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll(".cv-download").forEach((link) => {
    link.href = pdfs[language];
  });
  themeToggle.setAttribute("aria-label", copy.themeLabel);
  document.title = copy.title;
  document.querySelector('meta[name="description"]').setAttribute("content", copy.description);
  storage.set("pf-language", language);
}

function setTheme(theme) {
  const selected = theme === "dark" ? "dark" : "light";
  root.dataset.theme = selected;
  themeColor.setAttribute("content", selected === "dark" ? "#141916" : "#eee8dc");
  storage.set("pf-theme-editorial", selected);
}

languageSelect.addEventListener("change", (event) => setLanguage(event.target.value));
themeToggle.addEventListener("click", () => setTheme(root.dataset.theme === "dark" ? "light" : "dark"));

document.getElementById("copyEmail").addEventListener("click", async () => {
  try {
    await navigator.clipboard.writeText("paul@freyhofer.de");
  } catch {
    const fallback = document.createElement("textarea");
    fallback.value = "paul@freyhofer.de";
    document.body.appendChild(fallback);
    fallback.select();
    document.execCommand("copy");
    fallback.remove();
  }
  toast.textContent = translations[language].copied;
  toast.classList.add("visible");
  setTimeout(() => toast.classList.remove("visible"), 1800);
});

document.getElementById("year").textContent = new Date().getFullYear();
setTheme(storage.get("pf-theme-editorial") || "light");
setLanguage(language);

function onScroll() {
  const height = document.documentElement.scrollHeight - innerHeight;
  progress.style.width = `${height > 0 ? Math.min(100, scrollY / height * 100) : 0}%`;
}

addEventListener("scroll", onScroll, { passive: true });
onScroll();

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08 });
  document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
} else {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("visible"));
}
